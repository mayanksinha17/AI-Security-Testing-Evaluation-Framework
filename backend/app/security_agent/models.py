"""SQLAlchemy database models for Autonomous Security Testing Agent (Phase A, B & C).

Provides isolated persistence for:
1. Agent Execution Sessions (security_agent_sessions)
2. Security Execution Plans (security_execution_plans)
3. Individual Test Executions (security_test_executions) with multi-turn tracking
4. HTTP Evidence Records (security_http_evidence) with cryptographic SHA-256 integrity

These models are completely isolated and do not modify historical attack_results
or evaluation_runs tables.
"""

from datetime import datetime, timezone
import uuid
from sqlalchemy import Boolean, Column, DateTime, Float, ForeignKey, Integer, String, Text, text
from sqlalchemy.orm import relationship

from app.database.session import Base


class AgentExecutionSession(Base):
    """Tracks a user security testing session and high-level command."""
    __tablename__ = "security_agent_sessions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    title = Column(String(255), nullable=False, default="Autonomous Security Testing Session")
    command = Column(Text, nullable=False)
    user_confirmed_authorization = Column(Boolean, default=False, nullable=False)
    status = Column(
        String(50),
        nullable=False,
        default="CREATED",
    )  # CREATED, PLANNED, EXECUTING, COMPLETED, CANCELLED, FAILED
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    updated_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    plans = relationship(
        "SecurityExecutionPlan",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="SecurityExecutionPlan.created_at.desc()",
    )


class SecurityExecutionPlan(Base):
    """Tracks a concrete security execution plan generated by the autonomous agent."""
    __tablename__ = "security_execution_plans"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    session_id = Column(
        String(36),
        ForeignKey("security_agent_sessions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    target_url = Column(String(500), nullable=False)
    is_local_target = Column(Boolean, default=True, nullable=False)
    stage = Column(String(30), nullable=False, default="POST_MITIGATION")  # BASELINE or POST_MITIGATION
    total_tests = Column(Integer, nullable=False, default=0)
    completed_tests = Column(Integer, nullable=False, default=0)
    status = Column(
        String(50),
        nullable=False,
        default="PENDING",
    )  # PENDING, IN_PROGRESS, COMPLETED, CANCELLED, FAILED
    plan_metadata = Column(Text, nullable=True)  # Serialized JSON metadata
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    completed_at = Column(DateTime, nullable=True)

    session = relationship("AgentExecutionSession", back_populates="plans")
    executions = relationship(
        "SecurityTestExecution",
        back_populates="plan",
        cascade="all, delete-orphan",
        order_by="SecurityTestExecution.created_at.asc()",
    )


class SecurityTestExecution(Base):
    """Tracks an individual test execution against a specific target endpoint, with multi-turn lineage."""
    __tablename__ = "security_test_executions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    plan_id = Column(
        String(36),
        ForeignKey("security_execution_plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    scenario_id = Column(String(50), nullable=False, index=True)
    risk_id = Column(String(20), nullable=False, index=True)
    risk_name = Column(String(100), nullable=False)
    category = Column(String(50), nullable=False)  # OWASP_LLM or OWASP_AGENTIC
    test_type = Column(String(50), nullable=False)
    target_endpoint = Column(String(500), nullable=False)
    http_method = Column(String(10), nullable=False, default="POST")
    payload_id = Column(String(50), nullable=False)
    status = Column(
        String(30),
        nullable=False,
        default="PENDING",
    )  # PENDING, RUNNING, COMPLETED, FAILED, CANCELLED, BLOCKED_SCOPE
    verdict = Column(
        String(30),
        nullable=False,
        default="PENDING",
    )  # VULNERABLE, BLOCKED, PARTIAL, ERROR, NOT_RUN, INCONCLUSIVE, CANCELLED
    duration_ms = Column(Float, nullable=True)

    # Phase C Multi-Turn & Lineage Fields
    turn_number = Column(Integer, nullable=False, default=1)
    parent_execution_id = Column(String(36), nullable=True)
    chain_id = Column(String(36), nullable=True, index=True)
    payload_version = Column(String(20), nullable=False, default="v1")
    mutation_technique = Column(String(100), nullable=True)
    confidence = Column(Float, nullable=False, default=1.0)
    notes = Column(Text, nullable=True)

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    plan = relationship("SecurityExecutionPlan", back_populates="executions")
    evidence = relationship(
        "HttpEvidenceRecord",
        back_populates="execution",
        uselist=False,
        cascade="all, delete-orphan",
    )


class HttpEvidenceRecord(Base):
    """Stores full, unforgeable HTTP request and response evidence with secrets redacted and SHA-256 hash."""
    __tablename__ = "security_http_evidence"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    execution_id = Column(
        String(36),
        ForeignKey("security_test_executions.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )
    target_url = Column(String(500), nullable=False)
    http_method = Column(String(10), nullable=False)
    request_headers = Column(Text, nullable=True)  # Redacted JSON
    request_body = Column(Text, nullable=True)     # Redacted text/json
    response_status_code = Column(Integer, nullable=True)
    response_headers = Column(Text, nullable=True) # Redacted JSON
    response_body = Column(Text, nullable=True)    # Redacted text/json
    response_latency_ms = Column(Float, nullable=True)
    timestamp_sent = Column(DateTime, nullable=True)
    timestamp_received = Column(DateTime, nullable=True)
    error_message = Column(Text, nullable=True)
    evidence_sha256 = Column(String(64), nullable=True)  # Cryptographic SHA-256 integrity hash
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    execution = relationship("SecurityTestExecution", back_populates="evidence")


