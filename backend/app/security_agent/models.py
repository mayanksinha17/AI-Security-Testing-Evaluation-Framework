class SecurityEnterpriseReport(Base):
    """Phase E6 Additive Model: Persisted Enterprise Security Report.

    Stores complete, denormalized enterprise security reports with:
    - 10 standardized sections (Executive Summary, Scope, OWASP Matrix, Attack Graph,
      Findings Register, Evidence Ledger, RCA/CVSS Breakdown, Remediation Roadmap,
      Regression Analysis, Residual Risk & Signatures).
    - Cryptographic content integrity: SHA-256 digest (`report_hash`) calculated over
      canonical JSON serialization.
    - Cryptographic authenticity: HMAC-SHA256 signature (`hmac_signature`) computed using
      server secret key.
    - Zero-cascade archival safety: `session_id` and `plan_id` foreign keys configured with
      `ON DELETE SET NULL` so that report records survive source session/plan deletion.
    - Multi-format file paths: references to generated PDF, XLSX, CSV, and JSON artifacts.
    - Cryptographic artifact manifest (`artifact_manifest` JSON) binding all exported files
      to the canonical report snapshot.
    """

    __tablename__ = "security_enterprise_reports"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    report_id = Column(String(50), unique=True, nullable=False, index=True)
    session_id = Column(
        String(36),
        ForeignKey("security_agent_sessions.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    plan_id = Column(
        String(36),
        ForeignKey("security_execution_plans.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    report_type = Column(String(50), nullable=False, default="FULL_TECHNICAL")  # EXECUTIVE, FULL_TECHNICAL, COMPLIANCE
    target_scope = Column(String(500), nullable=False)
    report_title = Column(String(255), nullable=False)
    lead_auditor = Column(String(100), nullable=False, default="ApexShield Security Engine")

    # Metrics denormalized for rapid dashboard querying
    resilience_score = Column(Float, nullable=False, default=1.0)
    total_findings_count = Column(Integer, default=0, nullable=False)
    critical_findings_count = Column(Integer, default=0, nullable=False)
    high_findings_count = Column(Integer, default=0, nullable=False)
    medium_findings_count = Column(Integer, default=0, nullable=False)
    low_findings_count = Column(Integer, default=0, nullable=False)

    # Immutable Canonical Report Content (Denormalized 10-section JSON snapshot)
    report_data = Column(Text, nullable=False)

    # Generated Artifact File Paths (stored in reports archive directory)
    pdf_path = Column(String(500), nullable=True)
    excel_path = Column(String(500), nullable=True)
    csv_path = Column(String(500), nullable=True)
    json_path = Column(String(500), nullable=True)

    # Cryptographic Integrity & Authenticity Tokens
    report_hash = Column(String(64), nullable=False)        # SHA-256 Content Digest over canonical JSON
    hmac_signature = Column(String(64), nullable=False)     # HMAC-SHA256 Authenticity Signature
    signing_key_id = Column(String(50), nullable=False, default="v1_default")
    signing_algorithm = Column(String(50), nullable=False, default="HMAC-SHA256")

    # Verifiable Artifact Manifest (stores SHA-256 digests of all exported files, bound to canonical report)
    artifact_manifest = Column(Text, nullable=True)

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships with safe deletion
    session = relationship("AgentExecutionSession", foreign_keys=[session_id])
    plan = relationship("SecurityExecutionPlan", foreign_keys=[plan_id])


