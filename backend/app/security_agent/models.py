def migrate_phase_c_schema(engine) -> None:
    """Idempotently adds Phase C columns to existing SQLite tables if not present."""
    with engine.begin() as conn:
        try:
            cursor = conn.execute(text("PRAGMA table_info(security_test_executions);"))
            existing_cols = {row[1] for row in cursor.fetchall()}
            if existing_cols and "turn_number" not in existing_cols:
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN turn_number INTEGER DEFAULT 1;"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN parent_execution_id VARCHAR(36);"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN chain_id VARCHAR(36);"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN payload_version VARCHAR(20) DEFAULT 'v1';"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN mutation_technique VARCHAR(100);"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN confidence FLOAT DEFAULT 1.0;"))
                conn.execute(text("ALTER TABLE security_test_executions ADD COLUMN notes TEXT;"))

            cursor_ev = conn.execute(text("PRAGMA table_info(security_http_evidence);"))
            existing_ev_cols = {row[1] for row in cursor_ev.fetchall()}
            if existing_ev_cols and "evidence_sha256" not in existing_ev_cols:
                conn.execute(text("ALTER TABLE security_http_evidence ADD COLUMN evidence_sha256 VARCHAR(64);"))
        except Exception:
            pass  # If tables do not exist yet, Base.metadata.create_all handles creation


def migrate_phase_e4_schema(engine) -> None:
    """Idempotently adds Phase E4 tables and installs database-level immutability triggers (SEC-E4-004) and optimistic locking columns (SEC-E4-003)."""
    Base.metadata.create_all(
        bind=engine,
        tables=[
            SecurityFinding.__table__,
            SecurityFindingHistory.__table__,
            SecurityDecision.__table__,
        ],
    )

    with engine.begin() as conn:
        # 1. Add version_id column to security_findings if missing (SEC-E4-003)
        try:
            cols = {row[1] for row in conn.execute(text("PRAGMA table_info(security_findings);")).fetchall()}
            if "version_id" not in cols:
                conn.execute(text("ALTER TABLE security_findings ADD COLUMN version_id INTEGER NOT NULL DEFAULT 1;"))
            if "secondary_execution_id" not in cols:
                conn.execute(text("ALTER TABLE security_findings ADD COLUMN secondary_execution_id VARCHAR(36);"))
        except Exception:
            pass

        # 2. Database-level immutability triggers on security_finding_history (SEC-E4-004)
        try:
            conn.execute(text("""
                CREATE TRIGGER IF NOT EXISTS prevent_history_update
                BEFORE UPDATE ON security_finding_history
                BEGIN
                    SELECT RAISE(ABORT, 'security_finding_history is an immutable audit ledger: UPDATE operations are strictly prohibited');
                END;
            """))
            conn.execute(text("""
                CREATE TRIGGER IF NOT EXISTS prevent_history_delete
                BEFORE DELETE ON security_finding_history
                BEGIN
                    SELECT RAISE(ABORT, 'security_finding_history is an immutable audit ledger: DELETE operations are strictly prohibited');
                END;
            """))
        except Exception:
            pass


